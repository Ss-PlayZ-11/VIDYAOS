import { jsPDF } from 'jspdf';
import type { DailyNoteDocument, StudentProfile } from '../types/vidya';
import { formatMathText } from '../utils/studyEngine';

/**
 * Generates a clean, printable A4 PDF revision sheet using jsPDF.
 * Returns both the PDF Blob (for Google Drive multipart upload) and filename.
 */
export function buildDailyNotesPdf(
  note: DailyNoteDocument,
  profile: StudentProfile
): { blob: Blob; fileName: string; downloadLocally: () => void } {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 16;
  const contentWidth = pageWidth - margin * 2;
  let y = 18;

  const ensureSpace = (neededMm: number) => {
    if (y + neededMm > 276) {
      doc.addPage();
      y = 18;
    }
  };

  // Header Banner
  doc.setFillColor(15, 23, 42); // Slate 900
  doc.rect(0, 0, pageWidth, 32, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text('VidyaOS — Daily Short Revision & Formula Sheet', margin, 14);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.text(
    `Student: ${profile.name}  |  ${profile.grade} (${profile.board})  |  Date (IST): ${note.date}  |  Target: ${profile.targetPercentage}%`,
    margin,
    23
  );

  y = 42;
  doc.setTextColor(15, 23, 42);

  // Executive Summary
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('1. Daily Study & Alignment Summary', margin, y);
  y += 6;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  const summaryLines = doc.splitTextToSize(formatMathText(note.executiveSummary), contentWidth);
  doc.text(summaryLines, margin, y);
  y += summaryLines.length * 5 + 6;

  // Section Helper
  const renderSection = (heading: string, items: string[]) => {
    ensureSpace(20);
    doc.setDrawColor(226, 232, 240);
    doc.line(margin, y - 2, pageWidth - margin, y - 2);
    y += 4;

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11.5);
    doc.setTextColor(30, 41, 59);
    doc.text(heading, margin, y);
    y += 6;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.8);
    doc.setTextColor(51, 65, 85);

    items.forEach((item, idx) => {
      const bulletLines = doc.splitTextToSize(`${idx + 1}. ${formatMathText(item)}`, contentWidth - 4);
      ensureSpace(bulletLines.length * 5 + 3);
      doc.text(bulletLines, margin + 2, y);
      y += bulletLines.length * 4.8 + 2.5;
    });
    y += 4;
  };

  renderSection('2. Key Definitions & NCERT Theorems', note.keyDefinitions);
  renderSection('3. Essential Formulas & Identities', note.essentialFormulas);
  renderSection('4. Important Indian Board / NCERT Exam Tips', note.ncertExamTips);
  renderSection('5. Weak-Point Remediation Action Plan', note.weakAreaActionPlan);

  // Footer
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(8.5);
  doc.setTextColor(100, 116, 139);
  doc.text(
    `Generated by VidyaOS on ${note.date} (Asia/Kolkata IST) — Synced for ${profile.board} Exam Readiness`,
    margin,
    287
  );

  const fileName = `VidyaOS_Notes_${note.date}.pdf`;
  const blob = doc.output('blob');

  return {
    blob,
    fileName,
    downloadLocally: () => {
      doc.save(fileName);
    },
  };
}
